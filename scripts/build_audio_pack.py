#!/usr/bin/env python3
"""Build the installed W25Q128 PCM image and synthesizable descriptor table."""

from __future__ import annotations

import hashlib
import json
import re
import struct
import wave
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
SOURCE_DIR = ROOT / "音频"
OUT_DIR = ROOT / "audio_assets"
RTL_DIR = ROOT / "rtl" / "audio"
ALIGNMENT = 256
FLASH_TARGET = "W25Q128"
FLASH_CAPACITY = 16 * 1024 * 1024
MODE3_DIR = SOURCE_DIR
MODE3_GROUPS = (("M3_OBJ", 7), ("M3_CHAR", 7), ("SYS_M3", 5))

EXPECTED_COUNTS = {"SYS": 54, "PY": 47, "M2": 10}
STAGE_EXPECTED_COUNTS = {1: 15, 2: 7, 3: 7, 4: 8, 5: 5}
NAME_RE = re.compile(
    r"^(?:(SYS|PY|M2)_(\d{2})_|M2_S([1-5])_(\d{2})_).+\.wav$",
    re.IGNORECASE,
)


def source_sort_key(item: tuple[str, int, Path]) -> tuple[int, int]:
    """Keep the established global indices while using the new SYS_07..10 names.

    Global order is intentionally:
      SYS_00..06 -> PY_00..46 -> M2_00..09 -> SYS_07..53 -> M2_S1..S5
    This preserves the original indices 0..67.  New system prompts occupy
    68..110 and the 42 staged questions occupy 111..152.
    """
    category, local_index, _ = item
    if category == "SYS" and local_index <= 6:
        return (0, local_index)
    if category == "PY":
        return (1, local_index)
    if category == "M2":
        return (2, local_index)
    if category == "SYS" and local_index >= 7:
        return (3, local_index)
    if category.startswith("M2S"):
        stage = int(category[-1])
        return (3 + stage, local_index)
    return (9, local_index)


def align_up(value: int, alignment: int) -> int:
    return (value + alignment - 1) // alignment * alignment


def ordered_sources() -> list[tuple[str, int, Path]]:
    items: list[tuple[str, int, Path]] = []
    for path in SOURCE_DIR.glob("*.wav"):
        if any(path.name.startswith(category + "_") for category, _ in MODE3_GROUPS):
            continue  # Mode3 entries are appended below to preserve global indices.
        match = NAME_RE.match(path.name)
        if not match:
            raise SystemExit(f"unsupported audio filename: {path.name}")
        if match.group(1):
            category = match.group(1).upper()
            local_index = int(match.group(2))
        else:
            category = f"M2S{int(match.group(3))}"
            local_index = int(match.group(4))
        items.append((category, local_index, path))
    items.sort(key=source_sort_key)

    for category, expected in EXPECTED_COUNTS.items():
        indices = [local for cat, local, _ in items if cat == category]
        if indices != list(range(expected)):
            raise SystemExit(
                f"{category} indices must be 00..{expected - 1:02d}, got {indices}"
            )
    for stage, expected in STAGE_EXPECTED_COUNTS.items():
        category = f"M2S{stage}"
        indices = [local for cat, local, _ in items if cat == category]
        if indices != list(range(expected)):
            raise SystemExit(
                f"{category} indices must be 00..{expected - 1:02d}, got {indices}"
            )
    # Append only: all established indices and PCM addresses stay unchanged.
    for category, expected in MODE3_GROUPS:
        paths = sorted(MODE3_DIR.glob(f"{category}_*.wav"))
        indices = []
        for path in paths:
            match = re.fullmatch(re.escape(category) + r"_(\d{2})_[A-Za-z0-9_]+\.wav", path.name)
            if not match:
                raise SystemExit(f"unsupported mode3 audio filename: {path.name}")
            local_index = int(match.group(1))
            indices.append(local_index)
            items.append((category, local_index, path))
        if indices != list(range(1, expected + 1)):
            raise SystemExit(f"{category} indices must be 01..{expected:02d}, got {indices}")
    if len(items) > 255:
        raise SystemExit("audio entry count exceeds 8-bit count capacity")
    return items


def read_pcm(path: Path) -> tuple[bytes, int]:
    with wave.open(str(path), "rb") as wav:
        actual = {
            "channels": wav.getnchannels(),
            "sample_width": wav.getsampwidth(),
            "sample_rate": wav.getframerate(),
            "compression": wav.getcomptype(),
        }
        expected = {
            "channels": 1,
            "sample_width": 2,
            "sample_rate": 16000,
            "compression": "NONE",
        }
        if actual != expected:
            raise SystemExit(f"invalid WAV format for {path.name}: {actual}")
        sample_count = wav.getnframes()
        pcm = wav.readframes(sample_count)
    if len(pcm) != sample_count * 2:
        raise SystemExit(f"truncated PCM data in {path.name}")
    return pcm, sample_count


def write_descriptor(entries: list[dict[str, object]]) -> None:
    lines = [
        "// Generated by scripts/build_audio_pack.py. Do not edit manually.",
        "module audio_descriptor_rom(",
        "    input  wire [7:0]  audio_index,",
        "    output reg  [23:0] start_address,",
        "    output reg  [23:0] sample_count,",
        "    output reg         valid",
        ");",
        "always @* begin",
        "    start_address = 24'd0;",
        "    sample_count  = 24'd0;",
        "    valid         = 1'b0;",
        "    case (audio_index)",
    ]
    for entry in entries:
        lines.extend(
            [
                f"        8'd{entry['audio_index']}: begin // {entry['file_name']}",
                f"            start_address = 24'd{entry['start_address']};",
                f"            sample_count  = 24'd{entry['sample_count']};",
                "            valid         = 1'b1;",
                "        end",
            ]
        )
    lines.extend(["        default: begin end", "    endcase", "end", "endmodule", ""])
    (RTL_DIR / "audio_descriptor_rom.v").write_text("\n".join(lines), encoding="utf-8")


def write_index_header(entries: list[dict[str, object]]) -> None:
    lines = ["// Generated by scripts/build_audio_pack.py. Do not edit manually."]
    for entry in entries:
        stem = Path(str(entry["file_name"])).stem
        safe = re.sub(r"[^A-Za-z0-9]+", "_", stem).strip("_").upper()
        lines.append(f"`define AUDIO_{safe} 8'd{entry['audio_index']}")
    lines.append(f"`define AUDIO_ENTRY_COUNT 8'd{len(entries)}")
    lines.append("")
    (RTL_DIR / "audio_index.vh").write_text("\n".join(lines), encoding="utf-8")


def main() -> None:
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    RTL_DIR.mkdir(parents=True, exist_ok=True)
    image = bytearray()
    entries: list[dict[str, object]] = []

    for audio_index, (category, local_index, path) in enumerate(ordered_sources()):
        pcm, sample_count = read_pcm(path)
        start = align_up(len(image), ALIGNMENT)
        image.extend(b"\x00" * (start - len(image)))
        image.extend(pcm)
        entries.append(
            {
                "audio_index": audio_index,
                "category": category,
                "local_index": local_index,
                "file_name": path.name,
                "start_address": start,
                "sample_count": sample_count,
                "byte_count": len(pcm),
                "duration_seconds": sample_count / 16000.0,
                "pcm_sha256": hashlib.sha256(pcm).hexdigest(),
            }
        )

    if len(image) > FLASH_CAPACITY:
        raise SystemExit(f"audio image is {len(image)} bytes, exceeds {FLASH_TARGET} capacity")

    image_path = OUT_DIR / "audio.bin"
    image_path.write_bytes(image)
    manifest = {
        "format": {
            "sample_rate_hz": 16000,
            "channels": 1,
            "bits_per_sample": 16,
            "encoding": "signed PCM little-endian",
            "alignment_bytes": ALIGNMENT,
        },
        "flash": {
            "target": FLASH_TARGET,
            "capacity_bytes": FLASH_CAPACITY,
            "image_bytes": len(image),
            "free_bytes": FLASH_CAPACITY - len(image),
            "image_sha256": hashlib.sha256(image).hexdigest(),
        },
        "entry_count": len(entries),
        "entries": entries,
    }
    (OUT_DIR / "audio_manifest.json").write_text(
        json.dumps(manifest, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
    )
    write_descriptor(entries)
    write_index_header(entries)
    print(
        f"built {len(entries)} entries, {len(image)} bytes "
        f"({len(image) / 1024:.1f} KiB), sha256={manifest['flash']['image_sha256']}"
    )


if __name__ == "__main__":
    main()

